inline std::vector<uint8_t> fromHex(const char *hex) {
  std::vector<uint8_t> bytes;
  auto nibble = [](char c) -> uint8_t {
    if (c >= '0' && c <= '9')
      return c - '0';
    return 10 + (c - 'a');
  };
  for (const char *p = hex; p[0] && p[1]; p += 2)
    bytes.push_back(static_cast<uint8_t>(nibble(p[0]) << 4 | nibble(p[1])));
  return bytes;
}

