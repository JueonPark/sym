#ifndef BENCH_REFERENCE_PLAN_H
#define BENCH_REFERENCE_PLAN_H

#include <cstdint>
#include <vector>

namespace bench {

inline std::vector<uint8_t> referencePlanBytes() {
  static const char kHex[] =
      "52504c4e0000000001000000010000004e020000000100000000000000000100"
      "0000000000000002000000010000000000000000010000000101000000000000"
      "0001000000010000000000000000002000000004000000030000000000000000"
      "0140000000000000000501000000014000000000000000010000000140000000"
      "0000000003000000000000000001400000000000000005000000000100000001"
      "0000000000000000002000000004000000010000000000000002000000030000"
      "0004000000020000006230010000000140000000000000000100000000000000"
      "0005000000000000000000000000000140000000000000000504020000006e30"
      "0300000000000000000140000000000000000503000000014000000000000000"
      "0000000000040100000000000000000200000062310100000001400000000000"
      "0000030000000000000000014000000000000000050300000000000000000140"
      "0000000000000005020000006e31030000000000000000014000000000000000"
      "0501000000010100000000000000010000000101000000000000000000000001"
      "0000000100000000000000004000000000000000000000000400000000000001"
      "0000040000000400000001000000070100000001000000070000000001000000"
      "0702000000010000000703000000";
  std::vector<uint8_t> bytes;
  for (const char *p = kHex; p[0] && p[1]; p += 2) {
    auto nib = [](char c) {
      return static_cast<uint8_t>(c <= '9' ? c - '0' : 10 + c - 'a');
    };
    bytes.push_back(static_cast<uint8_t>(nib(p[0]) << 4 | nib(p[1])));
  }
  return bytes;
}

} // namespace bench

#endif // BENCH_REFERENCE_PLAN_H
